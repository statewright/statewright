#!/usr/bin/env node
// Keep the consumer examples and new-install/upgrade seed on one definition.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import vm from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
export const definition = JSON.parse(readFileSync(resolve(root, 'workflows/agentic-engineering.json'), 'utf8'));

// Capture the immutable, previously shipped seed, never rewrite its migration.
export function legacyTemplate() {
  let up;
  const records = [];
  class Collection { constructor(value) { Object.assign(this, value); } }
  class Record {
    constructor(collection) { this.collection = collection; this.data = {}; }
    set(key, value) { this.data[key] = value; }
  }
  vm.runInNewContext(readFileSync(resolve(root, 'self-hosted/pocketbase/pb_migrations/001_init_collections.js'), 'utf8'), {
    migrate(fn) { up = fn; }, Collection, Record, console: { log() {} },
  }, { timeout: 1000 });
  up({ save(value) { if (value instanceof Record) records.push(value); } });
  const seed = records.find(value => value.collection.name === 'workflow_templates' && value.data.name === 'bugfix');
  if (!seed) throw new Error('Original bugfix seed missing');
  return JSON.parse(JSON.stringify(seed.data));
}

// Function body is embedded twice: PB executes callbacks in separate scopes.
function seedEngineering(app, expected, replacement, description) {
  function stable(value) {
    if (value === null || typeof value !== 'object') return JSON.stringify(value);
    if (Array.isArray(value)) return '[' + value.map(stable).join(',') + ']';
    return '{' + Object.keys(value).sort().map(function(key) {
      return JSON.stringify(key) + ':' + stable(value[key]);
    }).join(',') + '}';
  }
  function decoded(record) {
    // PocketBase JSON fields may be exposed as a JSONRaw value, not a JS map.
    return JSON.parse(record.getString('definition'));
  }
  var expectedJSON = stable(expected);
  var templates = app.findRecordsByFilter('workflow_templates', 'name = "agentic-engineering"', 'id', 1, 0);
  if (!templates.length) {
    var template = new Record(app.findCollectionByNameOrId('workflow_templates'));
    template.set('name', 'agentic-engineering');
    template.set('definition', replacement);
    template.set('description', description);
    template.set('active', true);
    template.set('sort_order', 0);
    app.save(template);
  }
  // Never rewrite an old definition or its run lineage. Exact enabled old
  // starter owners receive the new starter, unless that name already exists.
  var lastId = '';
  while (true) {
    var records = app.findRecordsByFilter('workflows',
      'name = "bugfix" && template_source = "bugfix" && active = true && id > {:last}', 'id', 100, 0, {last: lastId});
    if (!records.length) break;
    for (var i = 0; i < records.length; i++) {
      var record = records[i];
      lastId = record.id;
      if (stable(decoded(record)) !== expectedJSON) continue;
      var owner = record.getString('owner');
      var filter = 'name = "agentic-engineering"';
      if (owner) filter += ' && owner = {:owner}';
      var existing = app.findRecordsByFilter('workflows', filter, 'id', 1, 0, {owner: owner});
      if (existing.length) continue;
      var workflow = new Record(app.findCollectionByNameOrId('workflows'));
      workflow.set('name', 'agentic-engineering');
      workflow.set('template_source', 'agentic-engineering');
      workflow.set('definition', replacement);
      workflow.set('active', true);
      if (owner) workflow.set('owner', owner);
      app.save(workflow);
    }
  }
}

export function migrationSource() {
  const legacy = legacyTemplate();
  const description = 'Evidence-led fixes, features, refactors and investigations. Verify and review, with a no-change path and one repair round.';
  return `/// <reference path="../pb_data/types.d.ts" />
// Generated by scripts/generate-engineering-workflow.mjs. Do not edit by hand.
// PocketBase runs each callback in a transaction. Existing data is never replaced.
migrate(function(app) {
  var expected = ${JSON.stringify(legacy.definition)};
  var replacement = ${JSON.stringify(definition)};
  ${seedEngineering.toString()}
  seedEngineering(app, expected, replacement, ${JSON.stringify(description)});
}, function(app) {
  // Deliberately retain user workflows and templates on downgrade. They may
  // already own runs or edits. A later upgrade is idempotent by owner and name.
});
`;
}

// Follow-up migration: the account, not the presence of an old template copy,
// determines eligibility. Keep the previous migration immutable.
export function accountMigrationSource() {
  return `/// <reference path="../pb_data/types.d.ts" />
// Generated by scripts/generate-engineering-workflow.mjs. Do not edit by hand.
migrate(function(app) {
  var collection = app.findCollectionByNameOrId('workflows');
  var template = app.findFirstRecordByData('workflow_templates', 'name', 'agentic-engineering');
  var definition = JSON.parse(template.getString('definition'));
  function seed(owner) {
    var filter = 'name = "agentic-engineering"';
    if (owner) filter += ' && owner = {:owner}';
    if (app.findRecordsByFilter('workflows', filter, 'id', 1, 0, {owner: owner}).length) return;
    var workflow = new Record(collection);
    workflow.set('name', 'agentic-engineering');
    workflow.set('template_source', 'agentic-engineering');
    workflow.set('definition', definition);
    workflow.set('active', true);
    if (owner) workflow.set('owner', owner);
    app.save(workflow);
  }
  if (!collection.fields.getByName('owner')) {
    seed('');
    return;
  }
  // Include accounts with no workflows at all, and paginate by stable ID.
  var lastId = '';
  while (true) {
    var users = app.findRecordsByFilter('users', 'id > {:last}', 'id', 100, 0, {last: lastId});
    if (!users.length) break;
    for (var i = 0; i < users.length; i++) {
      lastId = users[i].id;
      seed(lastId);
    }
  }
}, function(app) {
  // Retain added workflows and their history on downgrade; reapplying is safe.
});
`;
}

export function artifacts() {
  const pretty = value => JSON.stringify(value, null, 2) + '\n';
  return new Map([
    ['plugins/claude-code/statewright-engineering.json', pretty({ default: definition.id, workflows: { [definition.id]: definition }, upstream_servers: [] })],
    ['plugins/codex/workflows/agentic-engineering.json', pretty(definition)],
    ['crates/engine/tests/fixtures/agentic-engineering.json', pretty(definition)],
    ['self-hosted/pocketbase/pb_migrations/009_agentic_engineering.js', migrationSource()],
    ['self-hosted/pocketbase/pb_migrations/010_engineering_all_accounts.js', accountMigrationSource()],
  ]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const flags = process.argv.slice(2);
  if (flags.some(flag => !['--check', '--print-migration', '--print-account-migration'].includes(flag))) throw new Error('Unknown option');
  if (flags.includes('--print-migration')) process.stdout.write(migrationSource());
  else if (flags.includes('--print-account-migration')) process.stdout.write(accountMigrationSource());
  else for (const [path, contents] of artifacts()) {
    const target = resolve(root, path);
    if (flags.includes('--check')) {
      if (readFileSync(target, 'utf8') !== contents) throw new Error(`Stale generated artifact: ${path}`);
    } else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, contents); }
  }
}
